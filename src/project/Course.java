public class Course {

	// Attributes

	public String courseCode;
	public String title;

	// constructor

	public Course(String courseCode, String title) {
		this.courseCode = courseCode;
		this.title = title;
	}

	// Getter method

	public String getCourseCode() {
		return courseCode;
	}

	public String getTitle() {
		return title;
	}

}
